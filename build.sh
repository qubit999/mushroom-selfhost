#!/bin/bash
# Build the on-prem bundles and the capnp module lists that name them.
#
# wrangler bundles, on purpose: it's the same bundler as the hosted artifact, so on-prem and
# hosted come from one pipeline and can't drift like a hand-rolled build would. Nothing here
# deploys, and wrangler.build.jsonc carries no ids, routes or secrets.
#
# The module list is generated because wrangler emits each migration as a text module under a
# content-hashed name, and workerd's config can't glob. Hashes change with every migration edit.
set -euo pipefail

cd "$(dirname "$0")"
ROOT="$(pwd)"

build() {
  local worker="$1"
  # A worker without a wrangler.build.jsonc is skipped with a message saying so, rather than
  # silently.
  if [ ! -f "$worker/wrangler.build.jsonc" ]; then
    echo "==> skipping $worker (no $worker/wrangler.build.jsonc yet)"
    return 0
  fi
  echo "==> building $worker"

  # The Apple library is a real dependency of App Store activation (imported inside the
  # handler), so install it before bundling.
  ( cd "$worker-worker" && npm install --silent --no-audit --no-fund )

  # The pinned local copy, never npx's newest: this bundles the code holding a company's messages.
  ( cd "$worker" && "$ROOT/node_modules/.bin/wrangler" deploy --dry-run \
      --outdir="$ROOT/dist/$worker" -c wrangler.build.jsonc >/dev/null )

  # Module list: the entry, then every emitted .sql as a text module, named by bare filename as
  # the bundle imports them.
  local out="dist/$worker/modules.capnp"
  {
    echo "# GENERATED by selfhost/build.sh. Do not edit."
    echo "using Workerd = import \"/workerd/workerd.capnp\";"
    echo "const modules :List(Workerd.Worker.Module) = ["
    echo "  (name = \"entry.js\", esModule = embed \"entry.js\"),"
    for f in "dist/$worker"/*.sql; do
      [ -e "$f" ] || continue
      echo "  (name = \"$(basename "$f")\", text = embed \"$(basename "$f")\"),"
    done
    echo "];"
  } > "$out"

  echo "    $(ls -1 "dist/$worker"/*.sql 2>/dev/null | wc -l | tr -d ' ') migrations, $(du -h "dist/$worker/entry.js" | cut -f1) bundle"
}

build messaging
build files

echo "==> done"
